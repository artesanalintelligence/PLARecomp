"""Prewarm list for nvnshader_vkcheck (SPIR-V cache + VkPipelineCache).

Starts from <extract>/programs.txt (every VS+FS pair and CS in the RomFS, with the default
state) and adds the programs the game drew with a state that changes the SPIR-V
(integer attributes, transform feedback, points, dual source, early-z...), taken from one or
more suyu caches (`vulkan.bin`).

  python prewarm_list.py <extract_dir> <output.txt> [vulkan.bin ...]

Output format: "vs fs cs n [; vs_state ; fs_state]" (see tools/state_line.h).
"""
from __future__ import annotations

import collections
import glob
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
import suyu_cache  # noqa: E402
from states_from_suyu import ATTR_LETTER, TOPO  # noqa: E402


def index_codes(extract):
    idx = collections.defaultdict(list)
    for p in glob.glob(os.path.join(extract, "shaders", "*.data")):
        d = open(p, "rb").read()
        off = 0x30 if d[:4] == bytes.fromhex("78563412") else 0
        idx[d[off:off + 0x60]].append((os.path.basename(p)[:-5], d[off:]))
    return idx


def find(idx, code):
    for h, body in idx.get(code[:0x60], []):
        m = min(len(body), len(code)) - 8
        if body[:m] == code[:m]:
            return h
    return None


def vs_state(fps):
    raw1, raw2 = struct.unpack_from("<II", fps, 0)
    kv = []
    topo = TOPO.get((raw1 >> 24) & 0xF, "triangles")
    if topo != "triangles":
        kv.append(f"topo={topo}")
        if topo == "points":
            kv.append(f"psize={struct.unpack_from('<f', fps, 28)[0]:g}")
    letters = []
    for i in range(32):
        a = struct.unpack_from("<I", fps, 112 + 4 * i)[0]
        letters.append(ATTR_LETTER.get((a >> 20) & 7, "F") if a & 1 else "F")
    if any(c != "F" for c in letters):
        kv.append("attribs=" + "".join(letters))
    if (raw1 >> 6) & 1:
        kv.append("xfb=1")
    return " ".join(kv)


def fs_state(fps):
    raw1, raw2 = struct.unpack_from("<II", fps, 0)
    kv = []
    if (raw1 >> 21) & 1:
        kv.append("dual=1")
    if (raw2 >> 4) & 1:
        kv.append("earlyz=1")
    alpha = (raw2 >> 1) & 7
    if alpha != 7:
        kv.append(f"alpha={alpha} aref={struct.unpack_from('<f', fps, 24)[0]:g}")
    return " ".join(kv)


def main():
    extract, out = sys.argv[1:3]
    caches = sys.argv[3:]
    lines = [l.rstrip("\n") for l in open(os.path.join(extract, "programs.txt"), encoding="utf-8")
             if l.strip() and not l.startswith("#")]
    extra = set()
    if caches:
        idx = index_codes(extract)
        for c in caches:
            _v, _g, recs = suyu_cache.load(c)
            for r in recs:
                if r.envs[0].stage == 5:
                    continue
                vs = next((find(idx, e.code) for e in r.envs if e.stage == 0), None)
                fs = next((find(idx, e.code) for e in r.envs if e.stage == 4), None) or "-"
                if not vs:
                    continue
                fps = r.key[48:]
                a, b = vs_state(fps), fs_state(fps)
                if a or b:
                    extra.add(f"{vs} {fs} - 1 ; {a} ; {b}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# vs fs cs n [; vs_state ; fs_state] -- generated by prewarm_list.py\n")
        f.write("\n".join(lines + sorted(extra)) + "\n")
    print(f"{len(lines)} programs with the default state + {len(extra)} with a different real state")


if __name__ == "__main__":
    main()
