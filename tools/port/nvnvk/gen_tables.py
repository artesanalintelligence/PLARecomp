#!/usr/bin/env python3
"""Generates the nvnvk tables from docs/port/data/nvn_sdk_map.csv.

  generated/nvn_funcs.inc   X-macro NVN_FN(index, name, sdk_offset, flags)
  (with --mod-json <dir>)   mod.json for the tracer (nvntrace) or the backend

Flags (NVT_* in trace/nvntrace.cpp):
  POST      also hook the return (return value and output pointers)
  DUMPARGS  dump the memory pointed to by X1..X7 on entry
  DUMPOBJ   dump the object (X0) on return (Initialize: driver's internal layout)
  USED      used by the game (static inventory)
  SETTER    pure setter/getter of a builder or state (game memory)
  HOT       called many times per frame: logged only in detail_frames
  bits 8-11 number of X arguments read (nvnarity.py; 0xF = unknown, indirect tail call)
"""
from __future__ import annotations
import argparse
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MAP = ROOT / "docs" / "port" / "data" / "nvn_sdk_map.csv"
TITLE_ID = "01001F5010DFA000"
BUILD_ID = "AEE8F150DDA1B5A838806E1A5EA6827AD9F3C51E"

POST, DUMPARGS, DUMPOBJ, USED, SETTER, HOT = 1, 2, 4, 8, 16, 32
HOT_NAMES = {"nvnDeviceGetTextureHandle", "nvnDeviceGetImageHandle", "nvnBufferMap", "nvnBufferGetSize",
             "nvnBufferGetAddress", "nvnSyncWait", "nvnDeviceGetTimestampInNanoseconds", "nvnQueueFenceSync",
             "nvnQueueSubmitCommands", "nvnQueuePresentTexture", "nvnWindowAcquireTexture", "nvnWindowSetCrop",
             "nvnSamplerCompare", "nvnMemoryPoolGetFlags", "nvnDeviceGetInteger"}

PURE_OBJECTS = ("BlendState", "ChannelMaskState", "ColorState", "DepthStencilState",
                "MultisampleState", "PolygonState", "VertexAttribState", "VertexStreamState",
                "TextureView", "BufferBuilder", "TextureBuilder", "SamplerBuilder",
                "MemoryPoolBuilder", "QueueBuilder", "WindowBuilder", "DeviceBuilder",
                "EventBuilder")


def flags_for(name: str, obj: str, used: bool, xargs: int, tail: str) -> int:
    f = USED if used else 0
    f |= (0xF if tail == "vcall" else min(xargs, 8)) << 8
    short = name[3:]
    if name in HOT_NAMES or short.startswith("CommandBuffer"):
        f |= HOT
    if obj in PURE_OBJECTS or any(short.startswith(o) and short[len(o):len(o) + 3] in ("Set", "Get")
                                  for o in PURE_OBJECTS):
        f |= SETTER
        if "Get" in short:
            f |= POST | DUMPARGS  # getters with output through a pointer (GetSwizzle, GetStencilOp...)
        return f
    f |= DUMPARGS
    if short.startswith("CommandBuffer") and "Get" not in short and short not in (
            "CommandBufferEndRecording", "CommandBufferInitialize"):
        return f  # no useful return: entry only
    f |= POST
    if short.endswith("Initialize"):
        f |= DUMPOBJ
    return f


def load():
    rows = list(csv.DictReader(open(MAP, newline="")))
    out = []
    for r in rows:
        used = r["used"] == "1"
        obj = r["object"]
        out.append((int(r["index"]), r["name"], int(r["sdk_offset"], 16),
                    flags_for(r["name"], obj, used, int(r.get("xargs") or 8), r.get("tail", ""))))
    return out


def write_inc(rows) -> Path:
    p = HERE / "generated" / "nvn_funcs.inc"
    p.parent.mkdir(exist_ok=True)
    lines = ["// Generated by tools/port/nvnvk/gen_tables.py from docs/port/data/nvn_sdk_map.csv.",
             "// NVN_FN(index, name, sdk offset, flags)"]
    for i, n, o, f in rows:
        lines.append(f"NVN_FN({i}, {n}, 0x{o:x}, 0x{f:x})")
    text = "\n".join(lines) + "\n"
    if not p.exists() or p.read_text(encoding="utf-8") != text:
        p.write_text(text, encoding="utf-8")
    return p


NVNVK_PRE_PREFIXES = ("nvnCommandBuffer", "nvnQueue", "nvnSync", "nvnWindow", "nvnMemoryPool",
                      "nvnProgramSetShaders", "nvnDeviceSetWindowOriginMode", "nvnDeviceSetDepthMode")
NVNVK_EXACT = {"nvnTextureInitialize", "nvnTextureWriteTexels", "nvnTextureWriteTexelsStrided"}
NVNVK_POST = {"nvnMemoryPoolInitialize", "nvnCommandBufferEndRecording", "nvnTextureInitialize"}


def write_mod_json(rows, out_dir: Path, mod_id: str, library: str, only_used: bool, config: dict,
                   pre: str, post: str) -> Path:
    hooks = []
    for i, n, o, f in rows:
        if mod_id == "nvnvk":
            # backend: only functions with a handler (see src/*.cpp Register*Hooks)
            if (not n.startswith(NVNVK_PRE_PREFIXES) or "Builder" in n) and n not in NVNVK_EXACT:
                continue
            h = {"module": "sdk", "offset": f"0x{o:x}", "pre": pre}
            if n in NVNVK_POST:
                h["post"] = post
            hooks.append(h)
            continue
        if only_used and not (f & USED):
            continue
        h = {"module": "sdk", "offset": f"0x{o:x}", "pre": pre}
        if f & POST:
            h["post"] = post
        hooks.append(h)
    doc = {"id": mod_id, "title_id": TITLE_ID, "build_id": BUILD_ID, "library": library,
           "enabled": True, "hooks": hooks, "config": config}
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / "mod.json"
    p.write_text(json.dumps(doc, indent=1), encoding="utf-8")
    return p


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mod", default="nvntrace", choices=["nvntrace", "nvnvk"])
    ap.add_argument("--mod-json", type=Path, help="folder to write mod.json into")
    ap.add_argument("--all", action="store_true", help="hook all 523 (default: only the used ones)")
    ap.add_argument("--trace-dir", default=r"D:\PLARecomp\traces\nvn")
    ap.add_argument("--max-mb", type=int, default=1500)
    ap.add_argument("--detail-frames", default="0-3,60-62,600-602,3000-3002")
    ap.add_argument("--mode", default="shadow", choices=["shadow", "exclusive"])
    ap.add_argument("--log-dir", default="D:/PLARecomp/logs/nvnvk")
    ap.add_argument("--capture-dir", default="")
    ap.add_argument("--capture-every", type=int, default=0)
    ap.add_argument("--capture-max", type=int, default=0)
    ap.add_argument("--validation", action="store_true")
    ap.add_argument("--capture-path", default="", help="capture for the offline replayer (.nvkc)")
    ap.add_argument("--capture-frames", type=int, default=1200)
    ap.add_argument("--no-present", action="store_true", help="no window of its own")
    ap.add_argument("--pipeline-cache", default=str(ROOT / "build" / "port" / "nvnshader" / "prewarm" / "pipelines.bin"))
    ap.add_argument("--pipeline-cache-out", default="D:/PLARecomp/cache/nvnvk-pipelines.bin")
    ap.add_argument("--extra", default="", help="extra config keys: key=value;key=value")
    args = ap.parse_args()
    rows = load()
    print(f"{write_inc(rows)}: {len(rows)} functions, {sum(1 for r in rows if r[3] & USED)} used")
    if args.mod_json:
        cfg = {"trace_dir": args.trace_dir, "max_mb": args.max_mb, "detail_frames": args.detail_frames}
        if args.mod == "nvnvk":
            cfg = {"mode": args.mode, "log_dir": args.log_dir, "capture_dir": args.capture_dir,
                   "capture_every": args.capture_every, "capture_max": args.capture_max,
                   "validation": args.validation, "present": not args.no_present, "vsync": False,
                   "shader_cache_dir": "D:/PLARecomp/cache/nvnvk-shaders",
                   "pipeline_cache": args.pipeline_cache.replace("\\", "/"),
                   "pipeline_cache_out": args.pipeline_cache_out,
                   "capture_path": args.capture_path, "capture_frames": args.capture_frames}
            for kv in filter(None, args.extra.split(";")):  # "key=value;key=value" (JSON or text value)
                k, _, v = kv.partition("=")
                try:
                    cfg[k.strip()] = json.loads(v)
                except json.JSONDecodeError:
                    cfg[k.strip()] = v
        if args.mod == "nvntrace":
            p = write_mod_json(rows, args.mod_json, "nvntrace", "nvntrace.dll", not args.all, cfg,
                               "nvt_pre", "nvt_post")
        else:
            p = write_mod_json(rows, args.mod_json, "nvnvk", "nvnvk.dll", not args.all, cfg,
                               "nvk_pre", "nvk_post")
        print(f"{p}: {len(json.loads(p.read_text())['hooks'])} hooks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
