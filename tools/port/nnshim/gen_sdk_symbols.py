#!/usr/bin/env python3
"""Generates generated/sdk_symbols.inc: sdk-module offsets of the internal SDK functions the
shim hooks and main does not import (SHIM(SDKX, ...) rows of src/shim_table.inc).

The game's sdk .dynsym also exports internal functions (nn::hid::detail::...), so looking
them up by name is enough. Needs the sdk module ELF (the one tools/port/inventory.py writes
to build/port/sdk.elf, or tools/extract nso2elf).

Usage:
  python tools/port/nnshim/gen_sdk_symbols.py [--elf build/port/sdk.elf]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from elftools.elf.elffile import ELFFile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SHIM_RE = re.compile(r'^SHIM\((\w+),\s*(\w+),\s*"([^"]+)",\s*(\w+)\)', re.M)


def family_of(mangled: str) -> str:
    m = re.match(r"_ZN2nn(\d+)(\w+)", mangled)
    if not m:
        return "other"
    n = int(m.group(1))
    return {"oe": "applet", "pl": "font", "diag": "err", "result": "err", "codec": "audio"}.get(m.group(2)[:n], m.group(2)[:n])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", type=Path, default=ROOT / "build" / "port" / "sdk.elf")
    ap.add_argument("--out", type=Path, default=HERE / "generated" / "sdk_symbols.inc")
    args = ap.parse_args(argv)

    # shim_table.inc plus other families' tables (audio_table.inc).
    tables = [HERE / "src" / "shim_table.inc"] + sorted(p for p in (HERE / "src").glob("*_table.inc")
                                                        if p.name != "shim_table.inc")
    wanted = [m for t in tables for site, _st, m, _fn in SHIM_RE.findall(t.read_text(encoding="utf-8"))
              if site == "SDKX"]
    with args.elf.open("rb") as fh:
        elf = ELFFile(fh)
        syms = {s.name: s["st_value"] for s in elf.get_section_by_name(".dynsym").iter_symbols() if s["st_value"]}
    lines = ["/* Generated by tools/port/nnshim/gen_sdk_symbols.py: do not edit by hand.",
             " * NN_SDKSYM(family, module, offset, \"mangled\"): internal SDK functions (not",
             " * imported by main) that the shim hooks at their definition. */"]
    missing = []
    for m in wanted:
        if m not in syms:
            missing.append(m)
            continue
        lines.append(f'NN_SDKSYM({family_of(m)}, sdk, {syms[m]:#x}, "{m}")')
    if missing:
        raise SystemExit(f"symbols without a definition in {args.elf}: {missing}")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{args.out}: {len(wanted)} symbols")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
