"""Generates docs/decomp/triage.md from the triage rows."""
from __future__ import annotations

import hashlib
from collections import Counter, defaultdict

from common import ROOT, Image, normalize_linked, words

DOC = ROOT / "docs" / "decomp" / "triage.md"


def _fmt(n):
    return f"{n:,}"


def _mb(n):
    return f"{n / 1048576:.2f}"


def write_markdown(rows, seg, fs):
    img = Image()
    total_n = len(rows)
    total_b = sum(r[1] for r in rows)
    n, b = Counter(), Counter()
    conf = defaultdict(Counter)
    for a, s, c, cf, _name, _src in rows:
        n[c] += 1
        b[c] += s
        conf[c][cf] += 1

    def group(c):
        return c.split(":")[0]

    gn, gb = Counter(), Counter()
    for c in n:
        gn[group(c)] += n[c]
        gb[group(c)] += b[c]

    # ---- estimate of the "real" game code ----
    game = [r for r in rows if r[2] == "game"]
    tiny = [r for r in game if r[1] <= 8]
    hashes = Counter()
    first = {}
    for r in game:
        try:
            ws = normalize_linked(words(img.read(r[0], r[1])))
        except ValueError:
            continue
        h = hashlib.sha1(repr(ws).encode()).digest()
        hashes[h] += 1
        first.setdefault(h, r)
    uniq_n = len(hashes)
    uniq_b = sum(first[h][1] for h in hashes)
    dup_b = sum(r[1] for r in game) - uniq_b
    big_uniq = [first[h] for h in hashes if first[h][1] > 8]
    big_uniq_b = sum(r[1] for r in big_uniq)
    gconf = conf["game"]
    a16 = sum(1 for r in game if r[0] % 16 == 0)

    L = []
    w = L.append
    w("# Triage of `main` functions (PLA 1.1.1)")
    w("")
    w("Generated by `tools/triage/triage.py` (do not edit by hand; it is regenerated). "
      "Data: `data/triage.csv` (`Address,Size,Category,Confidence,Name,Source`); "
      "this data is generated locally and is not in the public repo (see docs/PUBLISHING.md). "
      "Compiler and signature method: `docs/research/07-compiler-id.md`.")
    w("")
    w(f"Total: **{_fmt(total_n)} functions**, **{_fmt(total_b)} bytes** ({_mb(total_b)} MiB) of code in `.text`.")
    w("")
    w("## Summary by group")
    w("")
    w("| Group | Functions | % | Bytes | % | MiB |")
    w("|---|---:|---:|---:|---:|---:|")
    for g in sorted(gb, key=lambda k: -gb[k]):
        w(f"| {g} | {_fmt(gn[g])} | {100 * gn[g] / total_n:.1f} | {_fmt(gb[g])} | "
          f"{100 * gb[g] / total_b:.1f} | {_mb(gb[g])} |")
    w("")
    w("## Detail by category")
    w("")
    w("| Category | Functions | Bytes | % bytes | Confidence high / medium / low |")
    w("|---|---:|---:|---:|---|")
    for c in sorted(b, key=lambda k: -b[k]):
        cf = conf[c]
        w(f"| `{c}` | {_fmt(n[c])} | {_fmt(b[c])} | {100 * b[c] / total_b:.2f} | "
          f"{cf['high']} / {cf['medium']} / {cf['low']} |")
    w("")
    w("## How much game code really remains")
    w("")
    gtot = sum(r[1] for r in game)
    w(f"- Classified as `game`: **{_fmt(len(game))} functions, {_mb(gtot)} MiB** "
      f"({100 * gtot / total_b:.1f}% of `.text`). Confidence: {gconf['high']} high, "
      f"{gconf['medium']} medium, {gconf['low']} low.")
    w(f"- Trivial functions (<= 8 bytes: `ret`, one-instruction getters, stubs): "
      f"{_fmt(len(tiny))} ({_fmt(sum(r[1] for r in tiny))} bytes).")
    w(f"- Unique bodies (normalizing BL/ADRP/LO12 immediates): **{_fmt(uniq_n)} bodies, "
      f"{_mb(uniq_b)} MiB**. The remaining {_mb(dup_b)} MiB are identical copies "
      f"(templates instantiated with same-size types, nearly identical component vtables).")
    w(f"- Without trivial ones or duplicates: **~{_fmt(len(big_uniq))} functions, {_mb(big_uniq_b)} MiB**. "
      "That is the realistic bound of the game decompilation work.")
    w("- There is still library code that cannot be separated with these signals and "
      "is counted as game: unnamed instances of libc++/sol2/flatbuffers templates "
      "(the game was compiled with `-fno-rtti`, so there is no RTTI to give them away) and "
      "inlines from Havok/Wwise headers. From experience with other decomps, estimate "
      "an additional 10-20% of third-party templates inside `game`.")
    w(f"- Alignment: only {100 * a16 / max(len(game), 1):.0f}% of the game's functions "
      "start at a multiple of 16 (vs. 100% in Lua, OpenSSL, zlib and Oodle). With "
      "`-mcpu=cortex-a57`, clang 9 aligns to 16 except for `optsize`/`cold` functions "
      "(checked: `__attribute__((cold))` drops to `.p2align 2`). Alignment varies WITHIN "
      "a single TU (padded functions are interleaved), so it is not a per-file flag: "
      "the most likely hypothesis is **PGO** (functions the profile did not execute "
      "end up `cold` and are optimized for size; static initializers and sol2 bindings, "
      "which always run at startup, are 99-100% aligned to 16). For "
      "matching, each function at 4 bytes will need `cold` (or equivalent). See 07-compiler-id.md.")
    w("")
    w("## Identified libraries")
    w("")
    w("| Library | Type | How it was identified |")
    w("|---|---|---|")
    libs_how = {
        "lua": "exact signatures: Lua 5.3.4 compiled with clang 9.0.0 (524 of 533 identical; the remaining 9 are GF modifications in loadlib, loslib and luaopen_io) and real names",
        "zlib": "exact signatures of zlib 1.2.11 + 16-aligned stretch that contains them (`Libz_SigloMiddlewareInfo` inside)",
        "openssl": "paths `external/openssl/...` and errors `SSL_`/`X509` (OpenSSL 1.1.1 from NPLN)",
        "grpc": "RTTI (`grpc::`, `grpc_core::`, `grpc_impl::`) and paths `external/com_google_grpc_base/...`",
        "protobuf": "RTTI `google::protobuf::` and paths `third_party/protobuf`",
        "re2": "RTTI `re2::` and paths `external/com_github_google_re2`",
        "abseil": "RTTI `absl::` and strings",
        "upb": "paths `external/upb`",
        "webrtc": "RTTI `rtc::`/`cricket::` and paths `rtc_base` (used by NPLN)",
        "curl": "libcurl strings (`A libcurl function was given a bad argument`, cookies)",
        "libc++": "RTTI/symbols `std::__1::` (template instances)",
        "sol2": "strings `sol::detail::ctti_get_type_name() [T = ...]` (instances in the bindings TUs)",
        "boost": "strings `boost::detail::ctti<...>` (`boost::any`, ctti)",
        "havok": "RTTI `hk*`/`hknp*`/`hkai*`, paths `C:/projects/havok/sdk/hk2020_2_0_r1` and propagation through calls",
        "npln": "RTTI `nn::npln::`, `nn::async::`, generated protos (`net_nintendo_npln_proto`)",
        "pia": "RTTI `nn::pia::` and `pead::` (sead embedded in Pia 6.16.2)",
        "nintendoware": "RTTI `nn::ui2d::`, `nn::font::`, `nn::vfx::`",
        "wwise": "strings `AK::...`, `Wwise`, plugins (`Recorder:`), imports `nn::audio::`/`nn::codec::`",
        "oodle": "strings `OODLE ERROR`, paths `v:/devel/projects/oodle2/...`, `newlz`",
        "nvn": "strings `nvn*` (NVN function pointer loader)",
        "nn-gfx": "RTTI `nn::gfx::`",
    }
    for c in sorted(b, key=lambda k: -b[k]):
        if c.startswith("lib-"):
            kind, name = c.split(":")
            w(f"| {name} | {'open' if kind == 'lib-open' else 'closed'} | {libs_how.get(name, '')} |")
    w("")
    w("## Stretch map")
    w("")
    w("Contiguous stretches of the segmentation (>= 64 KiB; interleaved templates and thunks do not cut them):")
    w("")
    w("| From | To | Category | Bytes |")
    w("|---|---|---|---:|")
    OV = {"lib-open:libc++", "lib-open:sol2", "lib-open:boost", "compiler-generated", "sdk-glue"}
    runs = []
    for a, s, c, cf, name, src in rows:
        if c in OV or "header inline" in src:
            if runs:
                runs[-1][2] = a + s
                runs[-1][3] += s
            continue
        if runs and runs[-1][0] == c:
            runs[-1][2] = a + s
            runs[-1][3] += s
        else:
            runs.append([c, a, a + s, s])
    for c, a, e, s in runs:
        if s >= 64 * 1024:
            w(f"| `{a:#x}` | `{e:#x}` | {c} | {_fmt(s)} |")
    w("")
    w("General layout: the precompiled libraries come first (Oodle, Lua, Havok, "
      "curl, NintendoWare, the NPLN stack: gRPC + protobuf + OpenSSL + re2 + abseil + upb + "
      "webrtc, and Pia), then ~33 MiB of game code, and at the end Wwise and the bulk of Havok. "
      "The PLT stubs (`sdk-glue`) are at `0x71032a2390`-`0x71032a5690`.")
    w("")
    w("## Method")
    w("")
    w("1. **Per-function evidence** (`tools/triage/evidence.py`): RTTI and vtable names "
      "(Ghidra), PLT and imports, referenced strings (source paths, asserts, type names), "
      "exact signatures of Lua 5.3.4 and zlib 1.2.11 compiled with the identified compiler "
      "(`tools/triage/flirt.py`, relocations masked) and thunk patterns "
      "(`sub x0, x0, #N; b target`).")
    w("2. **Call graph** (all BL/B in `.text`): a function without evidence whose "
      "callers all have the same library inherits that label (libraries do not call "
      "the game). Outgoing calls count for less and are not propagated.")
    w("3. **Contiguity** (Viterbi): the linker preserves TU order, so each "
      "library forms contiguous stretches. The function sequence is segmented with a cost per "
      "library change; a short stretch without game evidence between two stretches of the same "
      "library is assigned to that library (`sandwich`).")
    w("4. **Overlay**: templates from header libraries (libc++, sol2, boost), Havok inlines with "
      "an RTTI name, thunks and initializers are labeled per function even if they fall "
      "inside a game TU.")
    w("")
    w("Confidence: `high` = own direct evidence (signature, RTTI, string, PLT) matching the "
      "stretch; `medium` = no own evidence but inside a large stretch or near anchors; "
      "`low` = only by contiguity in a small stretch, or with contradictory own evidence.")
    w("")
    w("## Regenerate")
    w("")
    w("```sh")
    w("python tools/triage/lua_compiler_id.py map      # Lua name->address map")
    w("python tools/triage/lua_compiler_id.py exact    # identical Lua functions")
    w("python tools/triage/flirt.py zlib lua           # exact signatures")
    w("python tools/triage/triage.py                   # data/triage.csv + this document")
    w("python tools/triage/tu_map.py                   # data/tu_map.csv")
    w("```")
    w("")
    w("## Known limitations")
    w("")
    w("- Wwise and other libraries without RTTI and with few strings are detected less well: the "
      "stretch `0x7102ca0000`-`0x7102d20a74` (DSP computation with `exp2f`, `tanf`, `rand`) is probably "
      "Wwise effect plugins and was left as `game` with low confidence. Likewise for "
      "`0x7102e36110`-`0x7102e59e7c` (between Wwise and Havok).")
    w("- Unnamed third-party template instances (no RTTI) remain as `game`.")
    w("- The exact boundaries between neighboring libraries without strings (e.g. Havok/curl at "
      "`0x71000db2a0`) may be off by a few functions.")
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {DOC}")
    for g in sorted(gb, key=lambda k: -gb[k]):
        print(f"{g:22s} {gn[g]:8d} {gb[g]:10d}")
    for c in sorted(b, key=lambda k: -b[k]):
        print(f"  {c:28s} {n[c]:8d} {b[c]:10d}")
    print(f"unique game without trivial ones: {len(big_uniq)} functions, {big_uniq_b} bytes")
