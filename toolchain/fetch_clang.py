#!/usr/bin/env python3
"""Downloads and extracts candidate clang/LLVM versions for Windows.

Each version ends up in ``toolchain/cache/clang-<ver>/`` with only what is needed:

    bin/clang.exe              (+ clang++.exe as a hard link, takes no extra space)
    bin/ld.lld.exe
    bin/llvm-objdump.exe, bin/llvm-objcopy.exe (if present in the installer)
    bin/*.dll                  (only the small MSVC/UCRT runtime DLLs)
    lib/clang/<ver>/include/   (internal headers: stddef.h, arm_neon.h, ...)
    libcxx-include/            (libc++ headers of the SAME LLVM version)
    VERSION.json               (URL and SHA-256 of what was downloaded)

Official sources:
  * NSIS installers ``LLVM-<ver>-win64.exe``: releases.llvm.org (8, 9) and
    github.com/llvm/llvm-project/releases (10 onwards).
  * ``libcxx-<ver>.src.tar.xz`` from the same sites.

The NSIS installers are opened with 7-Zip (``7z.exe``); it is looked up in the PATH, in
``C:\\Program Files\\7-Zip`` and in scoop. If it is missing, install it with
``scoop install 7zip`` or from https://www.7-zip.org.

Usage:
    python toolchain/fetch_clang.py                 # default versions (9-12)
    python toolchain/fetch_clang.py 8.0.0 13.0.0    # specific versions
    python toolchain/fetch_clang.py --all           # 8.0.0 ... 13.0.0
    python toolchain/fetch_clang.py --list          # show what is installed
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path

TOOLCHAIN_DIR = Path(__file__).resolve().parent
CACHE_DIR = TOOLCHAIN_DIR / "cache"
DOWNLOADS_DIR = CACHE_DIR / "downloads"

GH = "https://github.com/llvm/llvm-project/releases/download/llvmorg-{v}/{f}"
OLD = "https://releases.llvm.org/{v}/{f}"

# Version -> URL template. 8.x and 9.x have no installers on GitHub.
VERSIONS: dict[str, str] = {
    "8.0.0": OLD,
    "9.0.0": OLD,
    "10.0.0": GH,
    "11.0.0": GH,
    "12.0.0": GH,
    "13.0.0": GH,
}
DEFAULT_VERSIONS = ["9.0.0", "10.0.0", "11.0.0", "12.0.0"]

# Executables we keep (the rest of the installer is discarded).
KEEP_EXES = ["clang.exe", "ld.lld.exe", "llvm-objdump.exe", "llvm-objcopy.exe",
             "llvm-readobj.exe", "llvm-readelf.exe"]
# Runtime DLLs (small) that clang.exe may need on machines without the
# VC++ redistributable. The large ones (LLVM-C, LTO, libclang, lldb) are not copied.
KEEP_DLL_PREFIXES = ("api-ms-win-", "msvcp140", "vcruntime140", "ucrtbase", "concrt140")

# Minimal __config_site to use libc++ outside its CMake build.
# Nintendo uses libc++ on top of a musl-derived libc, so we imitate that.
CONFIG_SITE = """\
// Generated by toolchain/fetch_clang.py (not part of upstream libc++).
#ifndef _LIBCPP_CONFIG_SITE
#define _LIBCPP_CONFIG_SITE
#define _LIBCPP_ABI_VERSION 1
#define _LIBCPP_ABI_NAMESPACE __1
#define _LIBCPP_HAS_MUSL_LIBC
#define _LIBCPP_HAS_THREAD_API_PTHREAD
#define _LIBCPP_HAS_NO_VENDOR_AVAILABILITY_ANNOTATIONS
#endif
"""


def log(msg: str) -> None:
    print(f">>> {msg}", flush=True)


def find_7z() -> str:
    cands = [shutil.which("7z"), shutil.which("7za"),
             r"C:\Program Files\7-Zip\7z.exe",
             r"C:\Program Files (x86)\7-Zip\7z.exe",
             os.path.expanduser(r"~\scoop\apps\7zip\current\7z.exe")]
    for c in cands:
        if c and Path(c).is_file():
            return c
    sys.exit("error: 7-Zip not found. Install it with `scoop install 7zip` "
             "or from https://www.7-zip.org and try again.")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url: str, dest: Path) -> None:
    if dest.is_file() and dest.stat().st_size > 0:
        log(f"already downloaded: {dest.name}")
        return
    log(f"downloading {url}")
    tmp = dest.with_suffix(dest.suffix + ".part")
    req = urllib.request.Request(url, headers={"User-Agent": "pla-decomp-fetch/1.0"})
    with urllib.request.urlopen(req) as r, tmp.open("wb") as f:
        total = int(r.headers.get("Content-Length", 0))
        done = 0
        last = -1
        while chunk := r.read(1 << 20):
            f.write(chunk)
            done += len(chunk)
            if total:
                pct = done * 100 // total
                if pct // 10 != last:
                    last = pct // 10
                    print(f"    {pct:3d}% ({done >> 20} / {total >> 20} MiB)", flush=True)
    tmp.replace(dest)


def dir_size(path: Path) -> int:
    seen: set[tuple[int, int]] = set()
    total = 0
    for p in path.rglob("*"):
        if p.is_file():
            st = p.stat()
            key = (st.st_dev, st.st_ino)
            if key in seen:  # do not count hard links twice
                continue
            seen.add(key)
            total += st.st_size
    return total


def extract_installer(seven: str, installer: Path, version: str, out: Path) -> None:
    patterns = [f"bin\\{e}" for e in KEEP_EXES]
    patterns += [f"bin\\{p}*.dll" for p in KEEP_DLL_PREFIXES]
    patterns.append(f"lib\\clang\\{version}\\include\\*")
    # -y: overwrite; patterns that do not exist (e.g. llvm-readelf) are ignored.
    cmd = [seven, "x", "-y", f"-o{out}", str(installer), *patterns]
    res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if res.returncode not in (0, 1):  # 1 = warning (e.g. pattern without matches)
        print(res.stdout)
        sys.exit(f"error: 7z failed to extract {installer.name}")
    if not (out / "bin" / "clang.exe").is_file():
        print(res.stdout)
        sys.exit(f"error: clang.exe was not extracted from {installer.name}")
    # 7z may leave a $PLUGINSDIR folder if a pattern catches it.
    shutil.rmtree(out / "$PLUGINSDIR", ignore_errors=True)


def extract_libcxx(tarball: Path, version: str, out: Path) -> None:
    dest = out / "libcxx-include"
    if dest.is_dir():
        shutil.rmtree(dest)
    prefix = f"libcxx-{version}.src/include/"
    with tarfile.open(tarball) as tf:
        members = []
        for m in tf.getmembers():
            if m.name.startswith(prefix) and (m.isfile() or m.isdir()):
                m.name = m.name[len(prefix):]
                if m.name:
                    members.append(m)
        tf.extractall(dest, members=members, filter="data")
    # libc++ >= 12 includes <__config_site> from <__config>; in <= 11 the
    # build concatenated it. We generate the file and, if needed, include it.
    (dest / "__config_site").write_text(CONFIG_SITE, encoding="utf-8")
    cfg = dest / "__config"
    text = cfg.read_text(encoding="utf-8")
    if "include <__config_site>" not in text:
        cfg.write_text("#include <__config_site>\n" + text, encoding="utf-8")
    for junk in ("CMakeLists.txt", "__config_site.in"):
        (dest / junk).unlink(missing_ok=True)


def install(version: str, keep_downloads: bool, force: bool) -> None:
    if version not in VERSIONS:
        sys.exit(f"error: unknown version {version}; options: {', '.join(VERSIONS)}")
    out = CACHE_DIR / f"clang-{version}"
    stamp = out / "VERSION.json"
    if stamp.is_file() and not force:
        log(f"clang-{version} is already installed ({dir_size(out) >> 20} MiB)")
        return
    if platform.system() != "Windows":
        sys.exit("error: this script downloads the Windows binaries. On Linux/WSL "
                 "use the clang+llvm-<ver>-x86_64-linux-gnu-*.tar.xz tarballs.")

    seven = find_7z()
    DOWNLOADS_DIR.mkdir(parents=True, exist_ok=True)
    tmpl = VERSIONS[version]
    inst_name = f"LLVM-{version}-win64.exe"
    cxx_name = f"libcxx-{version}.src.tar.xz"
    inst = DOWNLOADS_DIR / inst_name
    cxx = DOWNLOADS_DIR / cxx_name
    download(tmpl.format(v=version, f=inst_name), inst)
    download(tmpl.format(v=version, f=cxx_name), cxx)

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    log(f"extracting {inst_name}")
    extract_installer(seven, inst, version, out)
    log(f"extracting libc++ {version} headers")
    extract_libcxx(cxx, version, out)

    clangpp = out / "bin" / "clang++.exe"
    try:
        os.link(out / "bin" / "clang.exe", clangpp)
    except OSError:
        shutil.copy2(out / "bin" / "clang.exe", clangpp)

    stamp.write_text(json.dumps({
        "version": version,
        "installer": {"url": tmpl.format(v=version, f=inst_name), "sha256": sha256(inst)},
        "libcxx": {"url": tmpl.format(v=version, f=cxx_name), "sha256": sha256(cxx)},
        "bin": sorted(p.name for p in (out / "bin").iterdir()),
    }, indent=2), encoding="utf-8")

    if not keep_downloads:
        inst.unlink(missing_ok=True)
        cxx.unlink(missing_ok=True)

    # Quick check.
    res = subprocess.run([str(out / "bin" / "clang.exe"), "--version"],
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    first = res.stdout.splitlines()[0] if res.stdout else "?"
    log(f"clang-{version} ready ({dir_size(out) >> 20} MiB): {first}")


def list_installed() -> None:
    found = False
    for d in sorted(CACHE_DIR.glob("clang-*")):
        if (d / "VERSION.json").is_file():
            found = True
            print(f"{d.name:15s} {dir_size(d) >> 20:5d} MiB  {d}")
    if not found:
        print("no clang installed in toolchain/cache/")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("versions", nargs="*", help="versions to install (e.g. 9.0.0)")
    ap.add_argument("--all", action="store_true", help="install 8.0.0 to 13.0.0")
    ap.add_argument("--list", action="store_true", help="list what is installed and exit")
    ap.add_argument("--keep-downloads", action="store_true",
                    help="do not delete the installers after extracting them")
    ap.add_argument("--force", action="store_true", help="reinstall even if it exists")
    args = ap.parse_args()

    if args.list:
        list_installed()
        return
    versions = list(VERSIONS) if args.all else (args.versions or DEFAULT_VERSIONS)
    for v in versions:
        install(v, args.keep_downloads, args.force)
    try:
        DOWNLOADS_DIR.rmdir()  # only if it was left empty
    except OSError:
        pass
    list_installed()


if __name__ == "__main__":
    main()
